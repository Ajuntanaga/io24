@lru_cache(maxsize=4)
def _slot_two_immediate_materialization_candidates(data):
    """Return raw Thumb decodes that carry the exact slot-two immediate.

    Thumb code is halfword aligned, so this intentionally inventories every
    halfword boundary in the immutable image.  A returned decode is only a raw
    candidate; the caller source-binds it separately before reporting a route.
    """
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    decoder.detail = True
    candidates = []
    for offset in range(0, len(data) - 4, 2):
        instructions = list(decoder.disasm(
            data[offset:offset + 4], FIRMWARE_BASE + offset, count=1))
        if not instructions:
            continue
        instruction = instructions[0]
        if any(operand.type == ARM_OP_IMM and
               operand.imm == STRUCTURED_STATE_ALTERNATE_SLOT_TWO_OBJECT_DEVICE_OFFSET
               for operand in instruction.operands):
            candidates.append((offset, instruction.bytes.hex(),
                               instruction.mnemonic, instruction.op_str))
    return tuple(candidates)


