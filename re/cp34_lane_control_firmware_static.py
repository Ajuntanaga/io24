@lru_cache(maxsize=4)
def _base_initializer_reachable_cfg(data):
    """Recover the direct base initializer's bounded Thumb control flow.

    Calls are treated as opaque fall-through operations.  Direct branches stay
    in the known initializer range, while a PC-writing non-branch instruction
    or ``bx lr`` is treated as a return.  This is an address/control-flow map,
    not a semantic decompilation.
    """
    entry = DEVICE_COMPONENT_TABLE_BASE_INITIALIZER_RAW_OFFSET
    fence = DEVICE_COMPONENT_TABLE_BASE_INITIALIZER_FUNCTION_FENCE_RAW_OFFSET
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    decoder.detail = True
    pending = [entry]
    instructions_by_offset = {}
    returns = []
    dynamic_pc_transfers = []

    while pending:
        offset = pending.pop()
        if offset in instructions_by_offset:
            continue
        _require(entry <= offset < fence,
                 "base initializer CFG leaves function fence: %#x" % offset)
        decoded = list(decoder.disasm(
            data[offset:offset + 4], FIRMWARE_BASE + offset, count=1))
        _require(decoded and decoded[0].address == FIRMWARE_BASE + offset,
                 "base initializer CFG does not decode at %#x" % offset)
        instruction = decoded[0]
        instructions_by_offset[offset] = instruction
        fallthrough = offset + len(instruction.bytes)
        immediate = next((operand.imm for operand in instruction.operands
                          if operand.type == ARM_OP_IMM), None)
        _reads, writes = instruction.regs_access()

        if instruction.group(CS_GRP_CALL):
            pending.append(fallthrough)
        elif instruction.group(CS_GRP_JUMP):
            if immediate is None:
                if (instruction.mnemonic == "bx" and any(
                        operand.type == ARM_OP_REG and operand.reg == ARM_REG_LR
                        for operand in instruction.operands)):
                    returns.append((offset, instruction.mnemonic,
                                    instruction.op_str))
                else:
                    dynamic_pc_transfers.append((offset, instruction.mnemonic,
                                                 instruction.op_str))
            else:
                target = immediate - FIRMWARE_BASE
                _require(entry <= target < fence,
                         "base initializer branch leaves function fence: %#x" %
                         target)
                if instruction.cc == ARM_CC_AL:
                    pending.append(target)
                else:
                    pending.extend((fallthrough, target))
        elif ARM_REG_PC in writes:
            returns.append((offset, instruction.mnemonic, instruction.op_str))
        else:
            pending.append(fallthrough)

    direct_call_offsets = tuple(
        offset for offset, instruction in sorted(instructions_by_offset.items())
        if instruction.group(CS_GRP_CALL))
    return (
        tuple(sorted(instructions_by_offset)),
        direct_call_offsets,
        tuple(sorted(returns)),
        tuple(sorted(dynamic_pc_transfers)),
    )


