    digest = hashlib.sha256(data).hexdigest()
    _require(len(data) == FIRMWARE_SIZE,
             "firmware size differs: %d" % len(data))
    _require(digest == FIRMWARE_SHA256,
             "firmware SHA-256 differs: %s" % digest)

    reset_copy = struct.unpack_from("<III", data, RESET_COPY_TABLE["raw_offset"])
    _require(reset_copy == (
        RESET_COPY_TABLE["source_address"],
        RESET_COPY_TABLE["destination_address"],
        RESET_COPY_TABLE["length"],
    ), "reset copy table differs: %r" % (reset_copy,))
    _require(
        RESET_COPY_TABLE["source_address"] - FIRMWARE_BASE ==
        RESET_RELOCATION["source_raw_start"],
        "reset copy source no longer maps to the raw ITCM start")
    _require(
        RESET_RELOCATION["source_raw_start"] + RESET_COPY_TABLE["length"] - 1 ==
        RESET_RELOCATION["source_raw_end_inclusive"],
        "reset copy length no longer matches inclusive raw end")
    _require(
        RESET_RELOCATION["source_raw_start"] + RESET_COPY_TABLE["length"] ==
        RESET_RELOCATION["source_raw_end_exclusive"],
        "reset copy length no longer matches exclusive raw end")

    slices = {}
    for name, (offset, size, expected) in FIRMWARE_CODE_SLICES.items():
        actual = hashlib.sha256(data[offset:offset + size]).hexdigest()
        _require(actual == expected,
                 "%s slice differs: %s" % (name, actual))
        slices[name] = {
            "offset": hex(offset),
            "size": size,
            "sha256": actual,
        }

    calls = {}
    for name, (call_offset, target_offset) in FIRMWARE_CALL_ANCHORS.items():
        actual = _thumb_call_target(data, call_offset, FIRMWARE_BASE + call_offset)
        expected = FIRMWARE_BASE + target_offset
