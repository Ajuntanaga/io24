@lru_cache(maxsize=4)
def _primary_slot_0x28_local_straight_line_dispatches(data):
    """Inventory bounded generic primary-slot calls in the pinned image.

    This is deliberately a syntactic, local-flow inventory.  It recognizes a
    vtable load, a `+0x28` slot load, and an immediate `blx` without crossing
    any branch or call.  It does not turn a generic matching slot into a Voice
    FX call: that requires a separately proven embedded-owner construction and
    preservation of the receiver in `r0` at the call boundary.
    """
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    decoder.detail = True
    decoder.skipdata = True
    instructions = [instruction for instruction in decoder.disasm(
        data, FIRMWARE_BASE) if instruction.id != 0]

    def is_control_flow(instruction):
        return (instruction.group(CS_GRP_CALL) or
                instruction.group(CS_GRP_JUMP))

    def is_memory_load(instruction, destination=None, displacement=None):
        if (not instruction.mnemonic.startswith("ldr") or
                len(instruction.operands) != 2):
            return False
        destination_operand, memory_operand = instruction.operands
        if (destination_operand.type != ARM_OP_REG or
                memory_operand.type != ARM_OP_MEM):
            return False
        return ((destination is None or
                 destination_operand.reg == destination) and
                (displacement is None or
                 memory_operand.mem.disp == displacement))

    def receiver_has_local_embedded_owner_construction(vtable_load_index,
                                                        receiver_register):
        for prior_index in range(
                vtable_load_index - 1, max(-1, vtable_load_index - 80), -1):
            instruction = instructions[prior_index]
            if is_control_flow(instruction):
                return False
            _read, written = instruction.regs_access()
            if receiver_register not in written:
                continue
            return (
                instruction.mnemonic in {"add", "add.w"} and
                len(instruction.operands) == 3 and
                instruction.operands[0].type == ARM_OP_REG and
                instruction.operands[0].reg == receiver_register and
                instruction.operands[2].type == ARM_OP_IMM and
                instruction.operands[2].imm == VOICEFX_EMBEDDED_OWNER_PRIMARY_OFFSET)
        return False

    def receiver_is_preserved_in_r0(vtable_load_index, call_index,
                                    receiver_register):
        last_r0_writer = None
        for instruction in instructions[vtable_load_index + 1:call_index]:
            if is_control_flow(instruction):
                return False
            _read, written = instruction.regs_access()
            if ARM_REG_R0 in written:
                last_r0_writer = instruction
        if receiver_register == ARM_REG_R0:
            return last_r0_writer is None
        if last_r0_writer is None or last_r0_writer.mnemonic != "mov":
            return False
        if len(last_r0_writer.operands) != 2:
            return False
        return (last_r0_writer.operands[0].type == ARM_OP_REG and
                last_r0_writer.operands[0].reg == ARM_REG_R0 and
                last_r0_writer.operands[1].type == ARM_OP_REG and
                last_r0_writer.operands[1].reg == receiver_register)

    dispatches = []
    for call_index, call in enumerate(instructions):
        if (call.mnemonic != "blx" or len(call.operands) != 1 or
                call.operands[0].type != ARM_OP_REG):
            continue
        callee_register = call.operands[0].reg

        slot_load_index = None
        for candidate_index in range(
                call_index - 1, max(-1, call_index - 17), -1):
            candidate = instructions[candidate_index]
            if is_control_flow(candidate):
                break
            if is_memory_load(candidate, callee_register,
                              VOICEFX_PRIMARY_STATE_APPLY_VTABLE_OFFSET):
                slot_load_index = candidate_index
                break
        if slot_load_index is None:
            continue

        vtable_register = instructions[slot_load_index].operands[1].mem.base
        vtable_load_index = None
        for candidate_index in range(
                slot_load_index - 1, max(-1, slot_load_index - 17), -1):
            candidate = instructions[candidate_index]
            if is_control_flow(candidate):
                break
            if is_memory_load(candidate, vtable_register, 0):
                vtable_load_index = candidate_index
                break
        if vtable_load_index is None:
            continue

        receiver_register = instructions[vtable_load_index].operands[1].mem.base
        source_bound = (
            receiver_has_local_embedded_owner_construction(
                vtable_load_index, receiver_register) and
            receiver_is_preserved_in_r0(
                vtable_load_index, call_index, receiver_register))
        dispatches.append((
            call.address - FIRMWARE_BASE,
            instructions[vtable_load_index].address - FIRMWARE_BASE,
            instructions[slot_load_index].address - FIRMWARE_BASE,
            source_bound,
        ))
    return tuple(dispatches)


