def _placement_evidence(data):
    """Verify candidate bytes without treating either span as patch approval."""
    itcm_start = ITCM_TRAMPOLINE_ONLY_SPAN["raw_start"]
    itcm_end = ITCM_TRAMPOLINE_ONLY_SPAN["raw_end"]
    itcm_size = itcm_end - itcm_start + 1
    _require(itcm_size == ITCM_TRAMPOLINE_ONLY_SPAN["size"],
             "ITCM candidate size differs from its inclusive bounds")
    _require(data[itcm_start:itcm_end + 1] == b"\xff" * itcm_size,
             "ITCM trampoline candidate is not all 0xff")

    zero_start = TRAILING_RAW_ZERO_FILL["raw_start"]
    zero_end = TRAILING_RAW_ZERO_FILL["raw_end"]
    zero_size = zero_end - zero_start + 1
    _require(data[zero_start:zero_end + 1] == b"\0" * zero_size,
             "trailing zero-fill range is not all zero")

    trailing_start = TRAILING_RAW_PLACEMENT_CANDIDATE["raw_start"]
    trailing_end = TRAILING_RAW_PLACEMENT_CANDIDATE["raw_end"]
    trailing_size = trailing_end - trailing_start + 1
    _require(zero_end + 1 == trailing_start,
             "trailing zero-fill and all-FF ranges are not contiguous")
    _require(trailing_end + 1 == len(data),
             "trailing placement candidate does not reach the raw-image end")
    _require(data[trailing_start:trailing_end + 1] == b"\xff" * trailing_size,
             "trailing placement candidate is not all 0xff")

    return {
        "itcm_ff_span": {
            name: (hex(value) if name.startswith("raw_") else value)
            for name, value in ITCM_TRAMPOLINE_ONLY_SPAN.items()
        } | {"raw_bytes_verified": True},
        "extension_body": "NO_SAFE_HOME",
        "model5": _model5_dispatch_evidence(data),
        "trailing_zero_fill": {
            name: hex(value) if name.startswith("raw_") else value
            for name, value in TRAILING_RAW_ZERO_FILL.items()
        } | {"size": zero_size, "raw_bytes_verified": True},
        "trailing_raw_candidate": {
            name: hex(value) if name.startswith("raw_") else value
            for name, value in TRAILING_RAW_PLACEMENT_CANDIDATE.items()
        } | {"size": trailing_size, "raw_bytes_verified": True},
    }


def _model5_dispatch_evidence(data):
    """Prove the stock selector still accepts model 5 before rejecting reuse."""
    _require_thumb_instruction(data, 0x5539C, "movs", "r0, #6")
    _require_thumb_instruction(data, 0x5539E, "cmp", "r0, r5")
    _require_thumb_instruction(data, 0x553A0, "ble", "#0x600753c4")
    _require_thumb_instruction(data, 0x553A6, "str", "r5, [r4, #0x18]")
    return {
        "selector_raw_offset": "0x55388",
        "rejection_threshold": 6,
        "accepted_model_ids": [0, 1, 2, 3, 4, 5],
        "status": MODEL5_PLACEMENT_STATUS,
        "raw_bytes_verified": True,
    }


def _veneer_target(data, veneer_offset):
    """Return the Thumb literal target of a standard veneer."""
    _require(data[veneer_offset:veneer_offset + 4] == b"\x5f\xf8\x00\xf0",
             "veneer at %#x has unexpected opcode" % veneer_offset)
    literal, = struct.unpack_from("<I", data, veneer_offset + 4)
    return literal


def itcm_runtime_address(raw_offset):
    """Map a proved model-0 raw instruction offset into reset-relocated ITCM."""
    _require(raw_offset >= RESET_RELOCATION["source_raw_start"],
             "raw offset %#x precedes reset relocation" % raw_offset)
    return raw_offset - ITCM_FILE_TO_RUNTIME_DELTA


def itcm_raw_offset(runtime_address):
    """Map a Thumb/ITCM destination back to its raw application offset."""
    return (runtime_address & ~1) + ITCM_FILE_TO_RUNTIME_DELTA


