    _require_thumb_instruction(data, 0x5D9AA, "addw", "r6, r4, #0xc5c")
    _require_thumb_instruction(data, 0x5D9C8, "str", "r6, [sp, #8]")
    _require_thumb_instruction(data, 0x5D9F4, "ldr", "r0, [sp, #8]")
    _require_thumb_instruction(data, 0x5D9BC, "add.w", "r2, r4, #0x11e0")
    _require_thumb_instruction(data, 0x5D9CC, "mov", "r6, r2")
