def _cross_edge_scan(data, source_start, source_end, target_start, target_end):
    """List immediate cross-edges and indirect calls inside one validated slice."""
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    decoder.detail = True
    decoder.skipdata = True
    immediate_edges = []
    indirect_blx_sites = []
    for instruction in decoder.disasm(
            data[source_start:source_end], FIRMWARE_BASE + source_start):
        if instruction.id == 0:
            continue
        if instruction.mnemonic == "blx" and (
                not instruction.operands or
                instruction.operands[0].type != ARM_OP_IMM):
            indirect_blx_sites.append(hex(instruction.address - FIRMWARE_BASE))
        if not (instruction.group(CS_GRP_CALL) or instruction.group(CS_GRP_JUMP)):
            continue
        if len(instruction.operands) != 1:
            continue
        operand = instruction.operands[0]
        if operand.type != ARM_OP_IMM:
            continue
        target = operand.imm - FIRMWARE_BASE
        if target_start <= target < target_end:
            immediate_edges.append({
                "source_raw_offset": hex(instruction.address - FIRMWARE_BASE),
                "mnemonic": instruction.mnemonic,
                "target_raw_offset": hex(target),
            })
    return immediate_edges, indirect_blx_sites


@lru_cache(maxsize=4)
def _linear_decode_immediate_edges_to(data, target_raw_offset):
    """Inventory only immediate edges found by a full-image linear decode.

    This intentionally does not claim a complete control-flow graph.  It is a
    reproducible negative boundary for direct instruction sources, while
    dynamic and interprocedural routes remain outside this evidence.
    """
    edges, _indirect_sites = _cross_edge_scan(
        data, 0, len(data), target_raw_offset, target_raw_offset + 1)
    return tuple(
        (int(edge["source_raw_offset"], 16), edge["mnemonic"],
         int(edge["target_raw_offset"], 16))
        for edge in edges)


def _structured_state_dispatcher_boundary_evidence(data):
    """Keep source-bound ``Stat`` comparisons distinct from apply dispatch.

    The literal and comparison pairs prove that these are application-code tag
    checks, rather than host JSON spelling matches.  They do not identify a
    parser, a top-level apply caller, or the provenance of top-level apply's
    separately supplied ``r1`` record.
    """
    tag_bytes = struct.pack("<I", STRUCTURED_STATE_TAG_BIG_ENDIAN_VALUE)
    observed_literal_offsets = []
    cursor = 0
    while True:
        found = data.find(tag_bytes, cursor)
        if found < 0:
            break
        observed_literal_offsets.append(found)
        cursor = found + 1
    _require(tuple(observed_literal_offsets) ==
             STRUCTURED_STATE_TAG_LITERAL_RAW_OFFSETS,
             "structured-state tag literal inventory differs: %r" %
             [hex(offset) for offset in observed_literal_offsets])

    tag_comparisons = []
    tag_evidence_source_offsets = set()
    for (literal_raw_offset, literal_load_raw_offset,
         literal_load_operands, record_tag_load_raw_offset,
         record_tag_load_operands, tag_compare_raw_offset,
         tag_compare_mnemonic, tag_compare_operands) in \
            STRUCTURED_STATE_TAG_COMPARISON_SITES:
        tag_value, = struct.unpack_from("<I", data, literal_raw_offset)
        _require(tag_value == STRUCTURED_STATE_TAG_BIG_ENDIAN_VALUE,
                 "structured-state tag literal differs at %#x: %#x" %
                 (literal_raw_offset, tag_value))
        _require_thumb_instruction(
            data, literal_load_raw_offset, "ldr", literal_load_operands)
        _require(_thumb_pc_literal_raw_offset(data, literal_load_raw_offset) ==
                 literal_raw_offset,
                 "structured-state literal load at %#x targets a different "
                 "offset" % literal_load_raw_offset)
        _require_thumb_instruction(
            data, record_tag_load_raw_offset, "ldr",
            record_tag_load_operands)
        _require_thumb_instruction(
            data, tag_compare_raw_offset, tag_compare_mnemonic,
            tag_compare_operands)
        tag_evidence_source_offsets.update((
            literal_load_raw_offset, record_tag_load_raw_offset,
            tag_compare_raw_offset))
        tag_comparisons.append({
            "tag_literal_raw_offset": hex(literal_raw_offset),
            "literal_load_raw_offset": hex(literal_load_raw_offset),
            "record_tag_load_raw_offset": hex(record_tag_load_raw_offset),
            "tag_compare_raw_offset": hex(tag_compare_raw_offset),
        })

    immediate_apply_edges = _linear_decode_immediate_edges_to(
        data, VOICEFX_STATE_APPLY_RAW_OFFSET)
    expected_adjustor_edge = (
        VOICEFX_STATE_APPLY_ADJUSTOR_TAIL_BRANCH_RAW_OFFSET, "b.w",
        VOICEFX_STATE_APPLY_RAW_OFFSET)
    _require(immediate_apply_edges == (expected_adjustor_edge,),
             "immediate top-level apply edge inventory differs: %r" %
             (immediate_apply_edges,))
    _require(_thumb_branch_target(
        data, VOICEFX_STATE_APPLY_ADJUSTOR_TAIL_BRANCH_RAW_OFFSET,
        FIRMWARE_BASE + VOICEFX_STATE_APPLY_ADJUSTOR_TAIL_BRANCH_RAW_OFFSET) ==
        FIRMWARE_BASE + VOICEFX_STATE_APPLY_RAW_OFFSET,
        "secondary state-interface adjustor no longer tail-branches to "
        "top-level apply")
    tag_site_apply_edges = [
        edge for edge in immediate_apply_edges
        if edge[0] in tag_evidence_source_offsets]
    _require(not tag_site_apply_edges,
             "a structured-state tag evidence instruction now directly edges "
             "to top-level apply: %r" % (tag_site_apply_edges,))

