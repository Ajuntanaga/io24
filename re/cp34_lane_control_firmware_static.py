def _require(condition, message):
    if not condition:
        raise AnalysisError(message)


def _thumb_call_target(data, offset, address):
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    decoder.detail = True
    instructions = list(decoder.disasm(
        data[offset:offset + 4], address))
    _require(len(instructions) == 1,
             "call at %#x does not decode as one instruction" % offset)
    instruction = instructions[0]
    _require(instruction.mnemonic == "bl" and len(instruction.operands) == 1,
             "instruction at %#x is not a Thumb BL" % offset)
    operand = instruction.operands[0]
    _require(operand.type == ARM_OP_IMM,
             "BL at %#x does not have an immediate target" % offset)
    return operand.imm


def _thumb_branch_target(data, offset, address):
    """Return the immediate destination of one Thumb branch instruction."""
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    decoder.detail = True
    instructions = list(decoder.disasm(
        data[offset:offset + 4], address))
    _require(instructions and instructions[0].address == address,
             "branch at %#x does not decode as one instruction" % offset)
    instruction = instructions[0]
    _require(instruction.group(CS_GRP_JUMP) and
             not instruction.group(CS_GRP_CALL) and
             len(instruction.operands) == 1,
             "instruction at %#x is not an immediate Thumb branch" % offset)
    operand = instruction.operands[0]
    _require(operand.type == ARM_OP_IMM,
             "B at %#x does not have an immediate target" % offset)
    return operand.imm


def _thumb_pc_literal_raw_offset(data, offset):
    """Resolve one source-bound Thumb PC-relative literal load."""
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    decoder.detail = True
    instructions = list(decoder.disasm(
        data[offset:offset + 4], FIRMWARE_BASE + offset))
    _require(instructions and instructions[0].address == FIRMWARE_BASE + offset,
             "PC-relative load at %#x does not decode" % offset)
    instruction = instructions[0]
    _require(instruction.mnemonic.startswith("ldr") and
             len(instruction.operands) == 2,
             "instruction at %#x is not a literal load" % offset)
    memory_operand = instruction.operands[1]
    _require(memory_operand.type == ARM_OP_MEM and
             memory_operand.mem.base == ARM_REG_PC,
             "instruction at %#x is not PC-relative" % offset)
    literal_offset = ((offset + 4) & ~3) + memory_operand.mem.disp
    _require(0 <= literal_offset <= len(data) - 4,
             "literal at %#x is outside the pinned image" % literal_offset)
    return literal_offset


def _require_thumb_instruction(data, offset, mnemonic, operands):
    """Require one exact Thumb instruction from the pinned application."""
    decoder = Cs(CS_ARCH_ARM, CS_MODE_THUMB)
    instructions = list(decoder.disasm(
        data[offset:offset + 4], FIRMWARE_BASE + offset))
    _require(instructions and instructions[0].address == FIRMWARE_BASE + offset,
             "instruction at %#x does not decode" % offset)
    instruction = instructions[0]
    _require(instruction.mnemonic == mnemonic and instruction.op_str == operands,
             "instruction at %#x differs: %s %s" % (
                 offset, instruction.mnemonic, instruction.op_str))


