#!/usr/bin/env python3
"""Offline preconditions for CP34's per-lane private-reverb firmware fork.

This module deliberately does *not* build, modify, sign, stage, or upload a
firmware image.  It makes the custom-firmware work reviewable before any such
action can be considered: the stock application image is pinned, the existing
two-lane model-0 path is rechecked, and the parser/DSP patch must satisfy the
contract emitted below.

The stock firmware has one block-201/model-0 setting object and two private
reverb lanes.  The proposed extension retains the stock ``godv`` five-value
state and adds four optional ``voicefx`` record fields at structured-``Stat``
apply time.  The reset relocation is now source-bound: model-0 processing
executes from ITCM, and its final private-core dry/wet blend is identified.
Image emission remains intentionally blocked until parser/default storage and
safe patch placement are independently recovered.
"""

